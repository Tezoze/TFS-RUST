//! Deterministic Lua emitter for imported [`PendingNpcDefinition`]s.

use crate::npcs::{
    DialogueAction, DialogueExpr, DialoguePolicy, DialoguePredicate, DialogueProperty,
    DialogueRule, DialogueSituation, ExprOp, PendingNpcDefinition, SessionVar,
};

/// Emit a complete `NpcType` / `NpcDialogue` Lua definition script.
pub fn emit_npc_lua(pending: &PendingNpcDefinition) -> String {
    let mut out = String::new();
    out.push_str("-- Generated by import-npcs (NPC-2). Do not edit by hand.\n");
    if !pending.source_file.is_empty() {
        let source = std::path::Path::new(&pending.source_file)
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or(pending.source_file.as_str());
        out.push_str(&format!("-- Source: {source}\n"));
    }
    out.push('\n');
    out.push_str(&format!(
        "local npc = NpcType({})\n",
        lua_string(&pending.name)
    ));
    let a = &pending.appearance;
    out.push_str(&format!(
        "npc:appearance({{ lookType = {}, lookHead = {}, lookBody = {}, lookLegs = {}, lookFeet = {} }})\n",
        a.look_type, a.look_head, a.look_body, a.look_legs, a.look_feet
    ));
    let m = &pending.movement;
    out.push_str(&format!(
        "npc:movement({{ radius = {}, speed = {}, goStrength = {} }})\n",
        m.radius, m.speed, m.go_strength
    ));
    out.push_str(&format!("npc:health({})\n", pending.health_max));
    out.push_str(&format!("npc:sex({})\n", pending.sex));
    out.push_str(&format!("npc:race({})\n", pending.race));
    out.push('\n');

    if let Some(ref dialogue) = pending.dialogue {
        out.push_str("npc:dialogue(NpcDialogue({\n");
        out.push_str(&format!(
            "\tpolicy = {},\n",
            lua_string(match dialogue.policy {
                DialoguePolicy::QueuedSingleFocus => "queued_single_focus",
                DialoguePolicy::PerPlayer => "per_player",
            })
        ));
        out.push_str("\trules = {\n");
        for rule in &dialogue.rules {
            emit_rule(&mut out, rule, 2);
        }
        out.push_str("\t},\n");
        out.push_str("}))\n\n");
    }

    out.push_str("npc:register()\n");
    out
}

/// Stable filename stem from NPC display name.
pub fn definition_filename(name: &str) -> String {
    let mut s: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect();
    while s.contains("__") {
        s = s.replace("__", "_");
    }
    s.trim_matches('_').to_string() + ".lua"
}

fn emit_rule(out: &mut String, rule: &DialogueRule, indent: usize) {
    let pad = "\t".repeat(indent);
    // Emit fragment provenance for rules that were inlined from a .ndb include,
    // so grep/editors can find all copies of a shared fragment without needing
    // the now-deleted import pipeline.
    if rule.span.original_file.ends_with(".ndb") {
        let basename = std::path::Path::new(&rule.span.original_file)
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or(rule.span.original_file.as_str());
        if rule.span.original_line > 0 {
            out.push_str(&format!("{pad}-- from {basename}:{}\n", rule.span.original_line));
        } else {
            out.push_str(&format!("{pad}-- from {basename}\n"));
        }
    }
    out.push_str(&format!("{pad}{{\n"));
    if rule.span.original_line > 0 {
        out.push_str(&format!("{pad}\tline = {},\n", rule.span.original_line));
    }
    out.push_str(&format!("{pad}\twhen = {{\n"));
    for pred in &rule.predicates {
        emit_pred(out, pred, indent + 2);
    }
    out.push_str(&format!("{pad}\t}},\n"));
    out.push_str(&format!("{pad}\tactions = {{\n"));
    for act in &rule.actions {
        emit_action(out, act, indent + 2);
    }
    out.push_str(&format!("{pad}\t}},\n"));
    out.push_str(&format!("{pad}}},\n"));
}

fn emit_pred(out: &mut String, pred: &DialoguePredicate, indent: usize) {
    let pad = "\t".repeat(indent);
    match pred {
        DialoguePredicate::Situation { kind, .. } => {
            let s = match kind {
                DialogueSituation::Address => "address",
                DialogueSituation::Default => "default",
                DialogueSituation::Busy => "busy",
                DialogueSituation::Vanish => "vanish",
                DialogueSituation::AddressQueue => "addressqueue",
            };
            out.push_str(&format!("{pad}{{ situation = {} }},\n", lua_string(s)));
        }
        DialoguePredicate::Words { patterns, .. } => {
            out.push_str(&format!("{pad}{{ words = {{ "));
            for (i, p) in patterns.iter().enumerate() {
                if i > 0 {
                    out.push_str(", ");
                }
                out.push_str(&lua_string(p));
            }
            out.push_str(" } },\n");
        }
        DialoguePredicate::Select { .. } => {
            out.push_str(&format!("{pad}{{ select = true }},\n"));
        }
        DialoguePredicate::NumericCapture { slot, .. } => {
            out.push_str(&format!("{pad}{{ capture = {slot} }},\n"));
        }
        DialoguePredicate::Property { name, .. } => {
            out.push_str(&format!(
                "{pad}{{ property = {} }},\n",
                lua_string(property_name(*name))
            ));
        }
        DialoguePredicate::Expression { expr, op, rhs, .. } => {
            out.push_str(&format!(
                "{pad}{{ expr = {}, op = {}, rhs = {} }},\n",
                emit_expr(expr),
                lua_string(op_str(*op)),
                emit_expr(rhs)
            ));
        }
        DialoguePredicate::Custom { name, .. } => {
            out.push_str(&format!("{pad}{{ custom = {} }},\n", lua_string(name)));
        }
    }
}

fn emit_action(out: &mut String, act: &DialogueAction, indent: usize) {
    let pad = "\t".repeat(indent);
    match act {
        DialogueAction::Say { text, .. } => {
            out.push_str(&format!("{pad}{{ say = {} }},\n", lua_string(text)));
        }
        DialogueAction::SetSession { var, expr, .. } => {
            out.push_str(&format!(
                "{pad}{{ set = {{ var = {}, value = {} }} }},\n",
                lua_string(session_name(*var)),
                emit_expr(expr)
            ));
        }
        DialogueAction::SetHp { expr, .. } => {
            out.push_str(&format!("{pad}{{ hp = {} }},\n", emit_expr(expr)));
        }
        DialogueAction::Idle { .. } => out.push_str(&format!("{pad}{{ idle = true }},\n")),
        DialogueAction::Queue { .. } => out.push_str(&format!("{pad}{{ queue = true }},\n")),
        DialogueAction::Nop { .. } => out.push_str(&format!("{pad}{{ nop = true }},\n")),
        DialogueAction::StartPosition { pos, .. } => match pos {
            None => out.push_str(&format!("{pad}{{ startPosition = true }},\n")),
            Some((x, y, z)) => out.push_str(&format!(
                "{pad}{{ startPosition = {{ x = {x}, y = {y}, z = {z} }} }},\n"
            )),
        },
        DialogueAction::RepeatPrevious { .. } => {
            out.push_str(&format!("{pad}{{ repeatPrevious = true }},\n"));
        }
        DialogueAction::Create { item, count, .. } => {
            if matches!(count, DialogueExpr::Session(SessionVar::Amount)) {
                out.push_str(&format!(
                    "{pad}{{ create = {{ item = {} }} }},\n",
                    emit_expr(item)
                ));
            } else {
                out.push_str(&format!(
                    "{pad}{{ create = {{ item = {}, count = {} }} }},\n",
                    emit_expr(item),
                    emit_expr(count)
                ));
            }
        }
        DialogueAction::Delete { item, count, .. } => {
            if matches!(count, DialogueExpr::Session(SessionVar::Amount)) {
                out.push_str(&format!(
                    "{pad}{{ delete = {{ item = {} }} }},\n",
                    emit_expr(item)
                ));
            } else {
                out.push_str(&format!(
                    "{pad}{{ delete = {{ item = {}, count = {} }} }},\n",
                    emit_expr(item),
                    emit_expr(count)
                ));
            }
        }
        DialogueAction::CreateMoney { amount, .. } => {
            if matches!(amount, DialogueExpr::Session(SessionVar::Amount)) {
                out.push_str(&format!("{pad}{{ createMoney = true }},\n"));
            } else {
                out.push_str(&format!(
                    "{pad}{{ createMoney = {} }},\n",
                    emit_expr(amount)
                ));
            }
        }
        DialogueAction::DeleteMoney { amount, .. } => {
            if matches!(amount, DialogueExpr::Session(SessionVar::Price)) {
                out.push_str(&format!("{pad}{{ deleteMoney = true }},\n"));
            } else {
                out.push_str(&format!(
                    "{pad}{{ deleteMoney = {} }},\n",
                    emit_expr(amount)
                ));
            }
        }
        DialogueAction::Burning { cycles, param, .. } => {
            out.push_str(&format!(
                "{pad}{{ burning = {{ cycles = {}, param = {} }} }},\n",
                emit_expr(cycles),
                emit_expr(param)
            ));
        }
        DialogueAction::Poison { cycles, param, .. } => {
            out.push_str(&format!(
                "{pad}{{ poison = {{ cycles = {}, param = {} }} }},\n",
                emit_expr(cycles),
                emit_expr(param)
            ));
        }
        DialogueAction::EffectMe { effect_id, .. } => {
            out.push_str(&format!("{pad}{{ effectMe = {effect_id} }},\n"));
        }
        DialogueAction::EffectOpp { effect_id, .. } => {
            out.push_str(&format!("{pad}{{ effectOpp = {effect_id} }},\n"));
        }
        DialogueAction::SetQuestValue {
            storage_id, value, ..
        } => {
            out.push_str(&format!(
                "{pad}{{ setQuestValue = {{ id = {storage_id}, value = {} }} }},\n",
                emit_expr(value)
            ));
        }
        DialogueAction::Profession { vocation, .. } => {
            out.push_str(&format!(
                "{pad}{{ profession = {} }},\n",
                emit_expr(vocation)
            ));
        }
        DialogueAction::TeachSpell { spell, .. } => {
            out.push_str(&format!("{pad}{{ teachSpell = {} }},\n", emit_expr(spell)));
        }
        DialogueAction::Summon { monster, .. } => {
            out.push_str(&format!("{pad}{{ summon = {} }},\n", lua_string(monster)));
        }
        DialogueAction::Teleport { x, y, z, .. } => {
            out.push_str(&format!(
                "{pad}{{ teleport = {{ x = {x}, y = {y}, z = {z} }} }},\n"
            ));
        }
        DialogueAction::Custom { name, .. } => {
            out.push_str(&format!("{pad}{{ custom = {} }},\n", lua_string(name)));
        }
    }
}

fn emit_expr(expr: &DialogueExpr) -> String {
    match expr {
        DialogueExpr::Lit(n) => n.to_string(),
        DialogueExpr::Session(v) => format!("{{ session = {} }}", lua_string(session_name(*v))),
        DialogueExpr::Capture { slot } => format!("{{ capture = {slot} }}"),
        DialogueExpr::Hp => "{ hp = true }".into(),
        DialogueExpr::Burning => "{ burning = true }".into(),
        DialogueExpr::Poison => "{ poison = true }".into(),
        DialogueExpr::CountMoney => "{ countMoney = true }".into(),
        DialogueExpr::Level => "{ level = true }".into(),
        DialogueExpr::MagicLevel => "{ magicLevel = true }".into(),
        DialogueExpr::Count { item } => format!("{{ count = {} }}", emit_expr(item)),
        DialogueExpr::QuestValue { storage_id } => format!("{{ questValue = {storage_id} }}"),
        DialogueExpr::Random { lo, hi } => format!("{{ random = {{ {lo}, {hi} }} }}"),
        DialogueExpr::SpellKnown { spell } => format!("{{ spellKnown = {} }}", emit_expr(spell)),
        DialogueExpr::SpellLevel { spell } => format!("{{ spellLevel = {} }}", emit_expr(spell)),
        DialogueExpr::Binary { op, lhs, rhs } => format!(
            "{{ binary = {{ op = {}, lhs = {}, rhs = {} }} }}",
            lua_string(op_str(*op)),
            emit_expr(lhs),
            emit_expr(rhs)
        ),
    }
}

fn session_name(v: SessionVar) -> &'static str {
    match v {
        SessionVar::Topic => "topic",
        SessionVar::Price => "price",
        SessionVar::Amount => "amount",
        SessionVar::Type => "type",
        SessionVar::Data => "data",
    }
}

fn property_name(p: DialogueProperty) -> &'static str {
    match p {
        DialogueProperty::Address => "address",
        DialogueProperty::Busy => "busy",
        DialogueProperty::Vanish => "vanish",
        DialogueProperty::Male => "male",
        DialogueProperty::Female => "female",
        DialogueProperty::Knight => "knight",
        DialogueProperty::Paladin => "paladin",
        DialogueProperty::Sorcerer => "sorcerer",
        DialogueProperty::Druid => "druid",
        DialogueProperty::Premium => "premium",
        DialogueProperty::Promoted => "promoted",
        DialogueProperty::PvpEnforced => "pvpenforced",
        DialogueProperty::NonPvp => "nonpvp",
        DialogueProperty::PzBlock => "pzblock",
    }
}

fn op_str(op: ExprOp) -> &'static str {
    match op {
        ExprOp::Add => "+",
        ExprOp::Sub => "-",
        ExprOp::Mul => "*",
        ExprOp::Eq => "=",
        ExprOp::Ne => "<>",
        ExprOp::Lt => "<",
        ExprOp::Le => "<=",
        ExprOp::Gt => ">",
        ExprOp::Ge => ">=",
    }
}

fn lua_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\{}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
